export function openingPreview(moves: string[], maxFullMoves = 3): string {
  return moves
    .slice(0, maxFullMoves * 2)
    .map(
      (move, index) => `${index % 2 === 0 ? `${index / 2 + 1}. ` : ""}${move}`,
    )
    .join(" ");
}
